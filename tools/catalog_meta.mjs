// Writes js/catalog-meta.js: what the home screen shows about each region
// (subtitle, counts, operation, film) without loading the region's data.
//   node tools/catalog_meta.mjs          rewrite the file
//   node tools/catalog_meta.mjs --check  exit 1 if it is out of date
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const ctx = vm.createContext({ window: { ANATOMY: {} } });
const run = (file) => vm.runInContext(readFileSync(join(root, file), "utf8"), ctx, { filename: file });
run("js/catalog.js");
const { catalog, regions } = ctx.window.ANATOMY;

const meta = {};
for (const entry of catalog) {
  run(entry.scripts[0]);
  const r = regions[entry.id];
  const procs = r.procedures || (r.procedure ? [r.procedure] : []);
  const film = procs.map((p) => p.film && { ...p.film, title: p.title }).find(Boolean);
  meta[entry.id] = {
    subtitle: r.subtitle,
    structures: r.structures.filter((s) => s.layer !== "route").length,
    traced: r.structures.filter((s) => s.course).length,
    questions: (r.quiz || []).length,
    operations: procs.map((p) => p.title),
    ...(film ? { film } : {})
  };
}
const out = `// Generated by tools/catalog_meta.mjs from the region data files; do not edit by hand.\nwindow.ANATOMY.meta = ${JSON.stringify(meta, null, 2)};\n`;
const file = join(root, "js/catalog-meta.js");
if (process.argv.includes("--check")) {
  let now = "";
  try { now = readFileSync(file, "utf8"); } catch (e) {}
  if (now !== out) { console.error("js/catalog-meta.js is out of date: run node tools/catalog_meta.mjs"); process.exit(1); }
} else {
  writeFileSync(file, out);
  console.log("wrote js/catalog-meta.js for", Object.keys(meta).length, "regions");
}
